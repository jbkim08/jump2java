package s03_자바의기초;

public class 문자 {
    public static void main(String[] args) {
        //문자 자료형 char , 한따옴표 ''
        char a1 = 'A'; //65
        char a2 = 97; //'a'
        char a3 = '\u0061'; //'a'
        System.out.println(a1);
        System.out.println(a2);
        System.out.println(a3);
    }
}
